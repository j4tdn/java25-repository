-- Chay bang MySQL Workbench truoc khi chay Java.
-- Khong xoa/sua bang da ton tai. Neu da co schema giao vien, giu schema do.
CREATE DATABASE IF NOT EXISTS java25_shopping CHARACTER SET utf8mb4;
USE java25_shopping;

-- Hai bang toi thieu cho bai tap moi va cac lenh SELECT co ban.
-- Neu bang da ton tai thi CREATE IF NOT EXISTS khong thay doi cau truc cu.
CREATE TABLE IF NOT EXISTS T02_ITEM_GROUP (
    C02_ITEM_GROUP_ID BIGINT PRIMARY KEY,
    C02_ITEM_GROUP_NAME VARCHAR(255) NOT NULL,
    C02_STATUS INT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS T01_ITEM (
    C01_ITEM_ID BIGINT PRIMARY KEY,
    C01_ITEM_NAME VARCHAR(255) NOT NULL,
    C01_BUY_PRICE DECIMAL(15,2) NOT NULL DEFAULT 0,
    C01_MATERIAL VARCHAR(255),
    C01_COLOR VARCHAR(50),
    C01_ITEM_GROUP_ID BIGINT NOT NULL,
    FOREIGN KEY (C01_ITEM_GROUP_ID) REFERENCES T02_ITEM_GROUP(C02_ITEM_GROUP_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Bang rieng cho bai 10-11 vi file nguon khong kem schema khach hang.
CREATE TABLE IF NOT EXISTS LESSON17_CUSTOMER_ACCOUNT (
    ACCOUNT_ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    FULL_NAME VARCHAR(150) NOT NULL,
    EMAIL VARCHAR(254) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
