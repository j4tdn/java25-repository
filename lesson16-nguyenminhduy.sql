-- 28. Hiển thị mặt hàng có số lượng nhiều nhất trong mỗi loại hàng
WITH ITEM_STOCK AS (
    SELECT i.C01_ITEM_ID,
           i.C01_ITEM_NAME,
           COALESCE(i.C01_ITEM_GROUP_ID, sg.C03_ITEM_GROUP_ID) AS ITEM_GROUP_ID,
           COALESCE(SUM(d.C14_AMOUNT), 0) AS SO_LUONG
    FROM T01_ITEM i
    LEFT JOIN T03_SUB_ITEM_GROUP sg ON sg.C03_SIG_ID = i.C01_SIG_ID
    LEFT JOIN T14_ITEM_DETAIL d ON d.C14_ITEM_ID = i.C01_ITEM_ID
    GROUP BY i.C01_ITEM_ID,
             i.C01_ITEM_NAME,
             COALESCE(i.C01_ITEM_GROUP_ID, sg.C03_ITEM_GROUP_ID)
), XEP_HANG AS (
    SELECT s.*,
           DENSE_RANK() OVER (
               PARTITION BY s.ITEM_GROUP_ID
               ORDER BY s.SO_LUONG DESC
           ) AS RNK
    FROM ITEM_STOCK s
    WHERE s.ITEM_GROUP_ID IS NOT NULL
)
SELECT g.C02_ITEM_GROUP_ID,
       g.C02_ITEM_GROUP_NAME,
       x.C01_ITEM_ID,
       x.C01_ITEM_NAME,
       x.SO_LUONG
FROM XEP_HANG x
JOIN T02_ITEM_GROUP g ON g.C02_ITEM_GROUP_ID = x.ITEM_GROUP_ID
WHERE x.RNK = 1
ORDER BY g.C02_ITEM_GROUP_ID, x.C01_ITEM_ID;


