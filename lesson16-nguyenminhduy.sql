INSERT INTO T07_BILL (
    C07_ORDER_ID,
    C07_DELIVERY_FEE,
    C10_TOTAL_OF_MONEY
)
SELECT o.C06_ORDER_ID,
       CASE FLOOR(RAND() * 4)
           WHEN 0 THEN 20
           WHEN 1 THEN 30
           WHEN 2 THEN 40
           ELSE 50
       END AS C07_DELIVERY_FEE,
       0 AS C10_TOTAL_OF_MONEY
FROM T06_ORDER o
WHERE o.C06_ORDER_ID NOT IN (11, 12)
ORDER BY o.C06_ORDER_ID;

