-- 2. Tạo dữ liệu kiểm thử cho bảng T17_ORDER_STATUS_DETAIL

TRUNCATE TABLE T17_ORDER_STATUS_DETAIL;

INSERT INTO T17_ORDER_STATUS_DETAIL (
    C17_ORDER_ID,
    C17_ORDER_STATUS_ID,
    C17_EMPLOYEE_ID,
    C17_LAST_UPDATED
)
SELECT x.ORDER_ID,
       x.STATUS_ID,
       x.EMPLOYEE_ID,
       DATE_SUB(SYSDATE(), INTERVAL (x.MAX_STATUS_ID - x.STATUS_ID) DAY) AS LAST_UPDATED
FROM (
    SELECT o.C06_ORDER_ID AS ORDER_ID,
           s.STATUS_ID,
           CASE
               WHEN o.C06_ORDER_ID BETWEEN 1 AND 5 THEN 1
               WHEN o.C06_ORDER_ID BETWEEN 6 AND 8 THEN 2
               WHEN o.C06_ORDER_ID BETWEEN 9 AND 10 THEN 3
               WHEN o.C06_ORDER_ID BETWEEN 11 AND 12 THEN 4
               WHEN o.C06_ORDER_ID = 13 THEN 5
           END AS EMPLOYEE_ID,
           CASE
               WHEN o.C06_ORDER_ID BETWEEN 1 AND 5 THEN 5
               WHEN o.C06_ORDER_ID BETWEEN 6 AND 8 THEN 3
               WHEN o.C06_ORDER_ID BETWEEN 9 AND 10 THEN 4
               WHEN o.C06_ORDER_ID BETWEEN 11 AND 12 THEN 7
               WHEN o.C06_ORDER_ID = 13 THEN 6
           END AS MAX_STATUS_ID
    FROM T06_ORDER o
    JOIN (
        SELECT 1 AS STATUS_ID
        UNION ALL SELECT 2
        UNION ALL SELECT 3
        UNION ALL SELECT 4
        UNION ALL SELECT 5
        UNION ALL SELECT 6
        UNION ALL SELECT 7
    ) s
      ON (o.C06_ORDER_ID BETWEEN 1 AND 5  AND s.STATUS_ID BETWEEN 1 AND 5)
      OR (o.C06_ORDER_ID BETWEEN 6 AND 8  AND s.STATUS_ID BETWEEN 1 AND 3)
      OR (o.C06_ORDER_ID BETWEEN 9 AND 10 AND s.STATUS_ID BETWEEN 1 AND 4)
      OR (o.C06_ORDER_ID BETWEEN 11 AND 12 AND s.STATUS_ID = 7)
      OR (o.C06_ORDER_ID = 13 AND s.STATUS_ID IN (1, 2, 3, 4, 6))
    WHERE o.C06_ORDER_ID BETWEEN 1 AND 13
) x
ORDER BY x.ORDER_ID, x.STATUS_ID;

